// Real app, persistence and verification commands; no model/account calls.
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {execFileSync}=require('node:child_process');
const {pathToFileURL}=require('node:url');
const {_electron}=require('playwright-core');
(async()=>{
  const repo=path.resolve(__dirname,'..'),profile=fs.mkdtempSync(path.join(os.tmpdir(),'sudal-harness-link-'));
  const project=path.join(profile,'project'),home=path.join(profile,'home'),tabId='link-test';
  fs.mkdirSync(project);fs.mkdirSync(home);fs.mkdirSync(path.join(profile,'threads'));
  const git=(...args)=>execFileSync('git',['-c','core.hooksPath='+home,'-c','commit.gpgsign=false',...args],{cwd:project,windowsHide:true,stdio:'pipe'});
  git('init','-q');git('config','user.name','Fixture');git('config','user.email','fixture@example.invalid');
  fs.writeFileSync(path.join(project,'value.txt'),'original');git('add','.');git('commit','-qm','fixture');
  const disabled=path.join(profile,process.platform==='win32'?'disabled.cmd':'disabled');
  fs.writeFileSync(disabled,process.platform==='win32'?'@exit /b 1\r\n':'#!/bin/sh\nexit 1\n',{mode:0o755});
  fs.writeFileSync(path.join(profile,'cli-overrides.json'),JSON.stringify({codex:disabled,claude:disabled,agy:disabled}));
  fs.writeFileSync(path.join(profile,'trusted-folders.json'),JSON.stringify([project]));
  fs.writeFileSync(path.join(profile,'settings.json'),JSON.stringify({theme:'dark',warmTarget:'off',otter:false,language:'ko',notifyOnDone:'off'}));
  const now=Date.now(),legacy={type:'verify',ts:now,runId:'legacy-result',status:'passed',cwd:project,head:null,commands:[{cmd:'echo legacy-result',status:'passed',exitCode:0,output:'legacy output'}]};
  const thread=path.join(profile,'threads',tabId+'.jsonl');
  fs.writeFileSync(thread,[{type:'user_message',id:'request',ts:now-1,text:'검증 결과와 연결할 조건을 제안해 줘'},legacy].map(JSON.stringify).join('\n')+'\n');
  fs.writeFileSync(path.join(profile,'workspaces.json'),JSON.stringify({version:1,workspaces:[{id:'ws',name:'Harness',path:project,addedAt:now,lastUsedAt:now}],tabs:[{id:tabId,workspaceId:'ws',title:'검증 결과 연결',provider:'codex',policy:'ask',sessionId:null,createdAt:now,updatedAt:now,open:true}],openTabIds:[tabId],activeTabId:tabId}));
  const bootstrap=path.join(profile,'main.mjs');
  fs.writeFileSync(bootstrap,`import{app,BrowserWindow}from'electron';import{appendFileSync}from'node:fs';app.setPath('userData',${JSON.stringify(profile)});app.setPath('home',${JSON.stringify(home)});
    let seq=100000;globalThis.__propose=text=>{const event={type:'assistant_text',blockId:'proposal-'+Date.now(),ts:Date.now(),text};appendFileSync(${JSON.stringify(thread)},JSON.stringify(event)+'\\n');BrowserWindow.getAllWindows()[0].webContents.send('chat:event',{tabId:${JSON.stringify(tabId)},event,sequence:++seq});};
    await import(${JSON.stringify(pathToFileURL(path.join(repo,'out/main/index.js')).href)});`);
  const env={...process.env,USERPROFILE:home,HOME:home};delete env.ELECTRON_RUN_AS_NODE;delete env.ELECTRON_RENDERER_URL;
  let app;
  try{
    app=await _electron.launch({args:[bootstrap],cwd:repo,env,timeout:30000});
    const page=await app.firstWindow(),errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.locator('[data-composer] textarea').waitFor();
    const rpc=action=>page.evaluate(({id,action})=>window.sudal.chat.harness(id,action),{id:tabId,action});
    await rpc({type:'enable',enabled:true});
    const initial=await rpc({type:'start',goal:'연결 결과 검증',criteria:[{description:'명령이 통과한다',method:'echo verification-linked'},{description:'다른 조건',method:'별도 확인'}]});
    const task=initial.tasks.find(t=>t.status==='active'),detail=page.locator('[data-harness-detail]');
    const suggestion=page.locator('[data-harness-link-suggestion]');
    await suggestion.getByRole('button',{name:'이 결과로 확인할 조건 선택',exact:true}).click();
    await detail.getByText('검증 당시와 현재 코드가 같은지 확인할 수 없습니다.',{exact:false}).waitFor();
    await detail.getByRole('checkbox',{name:'명령이 통과한다',exact:true}).check();
    await detail.getByRole('button',{name:'검증 결과 연결',exact:true}).click();
    let state=await rpc({type:'snapshot'});
    assert.equal(state.tasks[0].evidence[0].result,'unconfirmed');
    assert.equal(state.tasks[0].evidence[0].timestamp,legacy.ts);
    const olderProposal='```sudal-evidence\n'+JSON.stringify({taskId:task.id,runId:legacy.runId,criteria:[{id:task.criteria[1].id,revision:1}]})+'\n```';
    await app.evaluate((_,text)=>globalThis.__propose(text),olderProposal);
    const run=await page.evaluate(id=>window.sudal.chat.verify(id,{commands:['echo verification-linked']}),tabId);
    assert.equal(run.ok,true);
    await suggestion.getByText('echo verification-linked',{exact:false}).waitFor();
    const source=(await page.evaluate(id=>window.sudal.chat.events(id),tabId)).findLast(e=>e.type==='verify'&&e.runId===run.runId);
    assert.ok(source.codeRevision);
    await assert.rejects(rpc({type:'linkVerification',taskId:task.id,runId:'unknown-run',criteria:task.criteria.map(({id,revision})=>({id,revision}))}));
    const proposal='```sudal-evidence\n'+JSON.stringify({taskId:task.id,runId:run.runId,criteria:[{id:task.criteria[0].id,revision:1}]})+'\n```';
    await app.evaluate((_,text)=>globalThis.__propose(text),proposal);
    await suggestion.getByText('AI가 이 결과를 다음 조건에 연결하도록 제안했습니다.',{exact:false}).waitFor();
    assert.equal((await rpc({type:'snapshot'})).tasks[0].evidence.length,1,'proposal alone must not change evidence');
    await page.screenshot({path:path.join(repo,'.sudal/harness-link-proposal.png')});
    await suggestion.getByRole('button',{name:'검증 결과 연결',exact:true}).click();
    state=await rpc({type:'snapshot'});
    assert.equal(state.tasks[0].evidence.length,2);
    assert.equal(state.tasks[0].evidence[1].result,'passed');
    assert.equal(state.tasks[0].evidence[1].codeRevision,state.revision);
    await suggestion.waitFor({state:'detached'});
    const linkAction={type:'linkVerification',taskId:task.id,runId:run.runId,criteria:[{id:task.criteria[0].id,revision:1}]};
    await rpc(linkAction);assert.equal((await rpc({type:'snapshot'})).tasks[0].evidence.length,2);
    await detail.getByRole('button',{name:'기존 검증 결과 연결',exact:true}).click();
    await detail.getByRole('button',{name:'echo verification-linked',exact:false}).click();
    await detail.getByRole('checkbox',{name:'명령이 통과한다',exact:false}).check();
    assert.equal(await detail.getByRole('button',{name:'검증 결과 연결',exact:true}).isDisabled(),true);
    await detail.getByRole('button',{name:'다시 검증하고 연결',exact:true}).click();
    const deadline=Date.now()+15000;
    do{state=await rpc({type:'snapshot'});if(state.tasks[0].evidence.length===3)break;await new Promise(r=>setTimeout(r,50));}while(Date.now()<deadline);
    assert.equal(state.tasks[0].evidence.length,3);
    await suggestion.waitFor({state:'detached'});
    const stale=await page.evaluate(id=>window.sudal.chat.verify(id,{commands:['echo stale-link']}),tabId);
    assert.equal(stale.ok,true,JSON.stringify(stale));
    await suggestion.getByText('echo stale-link',{exact:false}).waitFor();
    fs.writeFileSync(path.join(project,'value.txt'),'changed after verification');
    await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
    await suggestion.getByRole('button',{name:'이 결과로 확인할 조건 선택',exact:true}).click();
    await detail.getByRole('checkbox',{name:'다른 조건',exact:true}).check();
    await detail.getByRole('button',{name:'검증 결과 연결',exact:true}).click();
    state=await rpc({type:'snapshot'});
    const staleEvidence=state.tasks[0].evidence.find(e=>e.reference===stale.runId);
    assert.ok(staleEvidence);assert.notEqual(staleEvidence.codeRevision,state.revision);
    await page.screenshot({path:path.join(repo,'.sudal/harness-link-ui.png')});
    // A dismissed proposal must not swallow a later correction for the same result.
    const correctionState=await rpc({type:'start',goal:'정정 제안과 완료 위치',criteria:[{description:'조건 A',method:'check A'},{description:'조건 B',method:'check B'}]});
    const correctionTask=correctionState.tasks.find(t=>t.status==='active');
    const correctionRun=await page.evaluate(id=>window.sudal.chat.verify(id,{commands:['echo correction-result']}),tabId);
    await suggestion.getByText('echo correction-result',{exact:false}).waitFor();
    const correctedProposal=index=>'```sudal-evidence\n'+JSON.stringify({taskId:correctionTask.id,runId:correctionRun.runId,criteria:[{id:correctionTask.criteria[index].id,revision:1}]})+'\n```';
    await app.evaluate((_,text)=>globalThis.__propose(text),correctedProposal(0));
    await suggestion.getByText('조건 A',{exact:true}).waitFor();
    await suggestion.getByRole('button',{name:'건너뛰기',exact:true}).click();await suggestion.waitFor({state:'detached'});
    await app.evaluate((_,text)=>globalThis.__propose(text),correctedProposal(1));
    await suggestion.getByText('조건 B',{exact:true}).waitFor();
    assert.equal(await suggestion.getByText('조건 A',{exact:true}).count(),0);
    await suggestion.getByRole('button',{name:'검증 결과 연결',exact:true}).click();
    const corrected=(await rpc({type:'snapshot'})).tasks.find(t=>t.id===correctionTask.id);
    assert.equal(corrected.evidence.length,1);assert.equal(corrected.evidence[0].criterionId,correctionTask.criteria[1].id);
    await suggestion.waitFor({state:'detached'});
    await app.evaluate((_,text)=>globalThis.__propose(text),correctedProposal(0));
    await suggestion.getByText('조건 A',{exact:true}).waitFor();
    const attachedAt=await suggestion.getAttribute('data-harness-anchor');
    await suggestion.getByRole('button',{name:'검증 결과 연결',exact:true}).click();
    const ready=page.locator('[data-harness-ready]');await ready.waitFor();
    assert.equal(await ready.getAttribute('data-harness-anchor'),attachedAt);
    assert.notEqual(attachedAt,correctionRun.runId);
    const completedCorrection=(await rpc({type:'snapshot'})).tasks.find(t=>t.id===correctionTask.id);
    assert.equal(completedCorrection.evidence[0].timestamp,completedCorrection.evidence[1].timestamp);
    assert.ok(completedCorrection.evidence[1].recordedAt>=completedCorrection.evidence[1].timestamp);
    assert.deepEqual(errors,[]);
    await app.close();app=null;
    app=await _electron.launch({args:[bootstrap],cwd:repo,env,timeout:30000});
    const reopened=await app.firstWindow();await reopened.locator('[data-composer] textarea').waitFor();
    const restored=await reopened.evaluate(id=>window.sudal.chat.harness(id,{type:'snapshot'}),tabId);
    assert.equal(restored.tasks[0].evidence.length,4);
    assert.equal(restored.tasks[0].evidence[1].reference,run.runId);
    console.log(JSON.stringify({passed:true,legacyUnconfirmed:true,explicitLink:true,agentProposalRequiresAcceptance:true,trustedSource:true,freshness:true,idempotent:true,rerunLinkedCriteria:true,staleResult:true,restartPreserved:true}));
  }finally{
    await app?.close();
    const target=path.resolve(profile);if(path.dirname(target)!==path.resolve(os.tmpdir())||!path.basename(target).startsWith('sudal-harness-link-'))throw Error('Unexpected cleanup path');
    await fs.promises.rm(target,{recursive:true,force:true,maxRetries:10,retryDelay:50});
  }
})().catch(e=>{console.error(e);process.exitCode=1;});
